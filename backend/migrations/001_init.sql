-- Proposed Harbor HR schema. This is not an OrangeHRM database.
-- PostgreSQL. The application also creates these tables through SQLAlchemy.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    role VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS employees (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(60) NOT NULL,
    middle_name VARCHAR(60) NOT NULL DEFAULT '',
    last_name VARCHAR(60) NOT NULL,
    job_title VARCHAR(80) NOT NULL DEFAULT '',
    employment_status VARCHAR(80) NOT NULL DEFAULT '',
    sub_unit VARCHAR(80) NOT NULL DEFAULT '',
    supervisor VARCHAR(120) NOT NULL DEFAULT '',
    scope VARCHAR(20) NOT NULL DEFAULT 'current',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS sessions (
    token VARCHAR(64) PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS timesheets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_timesheet_employee_start UNIQUE (employee_id, period_start),
    CONSTRAINT ck_timesheet_period CHECK (period_end >= period_start),
    CONSTRAINT ck_timesheet_status CHECK (status IN ('pending', 'approved'))
);

CREATE TABLE IF NOT EXISTS timesheet_days (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timesheet_id INTEGER NOT NULL REFERENCES timesheets(id) ON DELETE CASCADE,
    work_date DATE NOT NULL,
    hours NUMERIC(4, 2) NOT NULL DEFAULT 0,
    description VARCHAR(200) NOT NULL DEFAULT '',
    CONSTRAINT uq_timesheet_day UNIQUE (timesheet_id, work_date),
    CONSTRAINT ck_timesheet_hours CHECK (hours >= 0 AND hours <= 24)
);

CREATE TABLE IF NOT EXISTS leave_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    leave_type VARCHAR(40) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    comment VARCHAR(200) NOT NULL DEFAULT '',
    CONSTRAINT ck_leave_period CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS candidates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_name VARCHAR(120) NOT NULL,
    vacancy VARCHAR(120) NOT NULL,
    hiring_manager VARCHAR(120) NOT NULL DEFAULT '',
    application_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    keywords VARCHAR(200) NOT NULL DEFAULT '',
    method VARCHAR(40) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS performance_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    CONSTRAINT ck_review_period CHECK (period_end >= period_start)
);

CREATE TABLE IF NOT EXISTS claims (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code VARCHAR(20) NOT NULL UNIQUE,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    event_name VARCHAR(120) NOT NULL,
    description VARCHAR(200) NOT NULL DEFAULT '',
    currency VARCHAR(8) NOT NULL,
    submitted_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Submitted',
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_claim_amount CHECK (amount >= 0)
);

CREATE TABLE IF NOT EXISTS employee_contacts (
    employee_id INTEGER PRIMARY KEY REFERENCES employees(id) ON DELETE CASCADE,
    street1 VARCHAR(120) NOT NULL DEFAULT '',
    street2 VARCHAR(120) NOT NULL DEFAULT '',
    city VARCHAR(80) NOT NULL DEFAULT '',
    state VARCHAR(80) NOT NULL DEFAULT '',
    postal_code VARCHAR(20) NOT NULL DEFAULT '',
    country VARCHAR(80) NOT NULL DEFAULT '',
    home_phone VARCHAR(40) NOT NULL DEFAULT '',
    mobile_phone VARCHAR(40) NOT NULL DEFAULT '',
    work_phone VARCHAR(40) NOT NULL DEFAULT '',
    work_email VARCHAR(120) NOT NULL DEFAULT '',
    other_email VARCHAR(120) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS emergency_contacts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    relationship VARCHAR(60) NOT NULL DEFAULT '',
    home_phone VARCHAR(40) NOT NULL DEFAULT '',
    mobile_phone VARCHAR(40) NOT NULL DEFAULT '',
    work_phone VARCHAR(40) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS vacancies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_title VARCHAR(80) NOT NULL,
    vacancy_name VARCHAR(120) NOT NULL,
    hiring_manager VARCHAR(120) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS performance_trackers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    tracker_name VARCHAR(120) NOT NULL,
    status VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS buzz_posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body VARCHAR(500) NOT NULL,
    author_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
