CREATE TABLE IF NOT EXISTS leave_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    leave_type VARCHAR(40) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    comment VARCHAR(200) NOT NULL DEFAULT '',
    CONSTRAINT ck_leave_period CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS candidates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_name VARCHAR(120) NOT NULL,
    vacancy VARCHAR(120) NOT NULL,
    hiring_manager VARCHAR(120) NOT NULL DEFAULT '',
    application_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    keywords VARCHAR(200) NOT NULL DEFAULT '',
    method VARCHAR(40) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS performance_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(40) NOT NULL,
    CONSTRAINT ck_review_period CHECK (period_end >= period_start)
);

CREATE TABLE IF NOT EXISTS claims (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code VARCHAR(20) NOT NULL UNIQUE,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    event_name VARCHAR(120) NOT NULL,
    description VARCHAR(200) NOT NULL DEFAULT '',
    currency VARCHAR(8) NOT NULL,
    submitted_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Submitted',
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_claim_amount CHECK (amount >= 0)
);
